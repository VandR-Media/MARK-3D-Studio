import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {runRecipe} from '../src/modeling-api.js';
const args=process.argv.slice(2);
const option=(name,def)=>{const index=args.indexOf(name);return index<0?def:args[index+1];};
const recipePath=option('--recipe','recipes/stylized-face-demo.json');
const recipe=JSON.parse(readFileSync(resolve(recipePath),'utf8'));
const outputDir=resolve(option('--out','dist/character/'+recipe.project.id));
const source=option('--input',null);
const sourceBytes=source?new Uint8Array(readFileSync(resolve(source))):null;
const result=runRecipe(recipe,{sourceBytes});
mkdirSync(outputDir,{recursive:true});
const hash=data=>createHash('sha256').update(data).digest('hex');
const glbName=recipe.project.id+'.glb';
writeFileSync(join(outputDir,glbName),result.bytes);
for(const [name,bytes] of result.snapshots)writeFileSync(join(outputDir,'checkpoint-'+name+'.glb'),bytes);
const manifest={
 apiVersion:result.recipeVersion,project:recipe.project.id,sourceRecipe:recipePath,
 recipeSha256:hash(readFileSync(resolve(recipePath))),
 glbSha256:hash(result.bytes),files:{glb:glbName,checkpoints:[...result.snapshots.keys()].map(n=>'checkpoint-'+n+'.glb')},
 summary:result.summary,audit:result.audit,warnings:result.warnings,commands:result.report,
 renders:{status:'generated by separate real WebGL2 Chromium workflow'}
};
writeFileSync(join(outputDir,'report.json'),JSON.stringify(manifest,null,2)+'\n');
writeFileSync(join(outputDir,'recipe.json'),JSON.stringify(recipe,null,2)+'\n');
console.log(JSON.stringify({outputDir,sha256:manifest.glbSha256,summary:manifest.summary,audit:manifest.audit,warnings:manifest.warnings},null,2));
